/**
 * Сообщение чата с ИИ-помощником.
 *
 * Пока это только верстка: сообщения живут в состоянии виджета и никуда не
 * уходят. Когда появится интеграция с `POST /chat` AI-сервиса, форма сообщения
 * не изменится — добавится только источник данных.
 */
export type ChatRole = 'bot' | 'user'

export type ChatMessage = {
  /** Локальный идентификатор для ключа списка. */
  id: string
  role: ChatRole
  text: string
}
